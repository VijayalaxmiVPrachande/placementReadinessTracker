import { NextResponse } from "next/server";
import { generateQuestionsFromGemini } from "@/lib/gemini";

/**
 * POST /api/mock-interview/generate
 * Body: { type: string, domain: string, difficulty: string }
 * Returns: { success: true, questions: string[] }
 */
export async function POST(req: Request) {
  try {
    const { type, domain, difficulty } = await req.json();

    if (!type || !domain || !difficulty) {
      return NextResponse.json(
        { success: false, error: "Missing required fields: type, domain, or difficulty." },
        { status: 400 }
      );
    }

    console.log("🎯 Generating mock interview questions:", { type, domain, difficulty });

    // 🧠 Generate from Gemini
    const text = await generateQuestionsFromGemini(type, domain, difficulty);

    // ✨ Format into a clean array
    const questions = text
      .split("\n")
      .map((line) => line.trim())
      .filter((line) => line && !/^\d+[\.\)]/.test(line)); // removes numbered prefixes

    if (questions.length === 0) {
      return NextResponse.json({
        success: false,
        error: "No valid questions generated by AI.",
      });
    }

    // ✅ Return only to the client — no DB writes
    return NextResponse.json({
      success: true,
      count: questions.length,
      questions,
    });
  } catch (err: any) {
    console.error("❌ Mock Interview Generation Error:", err);
    return NextResponse.json(
      { success: false, error: err.message || "Internal Server Error" },
      { status: 500 }
    );
  }
}
